// Waraqa CRM service worker: shows order notifications and opens the order
// when one is tapped. It caches nothing; the CRM always reads live data.

self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => event.waitUntil(self.clients.claim()));

self.addEventListener('push', (event) => {
  let data = {};
  try {
    data = event.data ? event.data.json() : {};
  } catch {
    data = { body: event.data ? event.data.text() : '' };
  }
  const title = data.title || 'Waraqa CRM';
  event.waitUntil(
    self.registration.showNotification(title, {
      body: data.body || '',
      tag: data.tag,
      renotify: Boolean(data.tag),
      icon: '/icons/icon-192.png',
      badge: '/icons/badge-96.png',
      data: { url: data.url || '/orders' },
    }),
  );
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const url = new URL((event.notification.data && event.notification.data.url) || '/', self.location.origin).href;
  event.waitUntil(
    (async () => {
      const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
      for (const client of windows) {
        if (new URL(client.url).origin !== self.location.origin) continue;
        try {
          // Focus first, while the tap still counts as user activation.
          // navigate() rejects for a window this worker doesn't control yet;
          // then fall through and open a fresh one instead of doing nothing.
          await client.focus();
          await client.navigate(url);
          return;
        } catch {
          break;
        }
      }
      await self.clients.openWindow(url);
    })(),
  );
});
